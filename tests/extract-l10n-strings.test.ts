// @vitest-environment node
import { parse } from '@babel/parser'
import { spawnSync } from 'node:child_process'
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterEach, describe, expect, it } from 'vitest'

const root = fileURLToPath(new URL('../', import.meta.url))
const cli = join(root, 'bin/nextcloud-vue-components.mjs')
const temporaryDirectories: string[] = []

function temporaryDirectory() {
  const directory = mkdtempSync(join(tmpdir(), 'nextcloud-vue-l10n-'))
  temporaryDirectories.push(directory)
  return directory
}

afterEach(() => {
  for (const directory of temporaryDirectories.splice(0)) {
    rmSync(directory, { recursive: true, force: true })
  }
})

function run(args: string[], cwd: string, executable = cli) {
  return spawnSync(process.execPath, [executable, ...args], { cwd, encoding: 'utf8' })
}

function fixture(files: Record<string, string>) {
  const directory = temporaryDirectory()
  mkdirSync(join(directory, 'bin'))
  mkdirSync(join(directory, 'lib'))
  copyFileSync(cli, join(directory, 'bin/nextcloud-vue-components.mjs'))
  symlinkSync(join(root, 'node_modules'), join(directory, 'node_modules'), 'dir')
  for (const [file, contents] of Object.entries(files)) {
    mkdirSync(dirname(join(directory, 'lib', file)), { recursive: true })
    writeFileSync(join(directory, 'lib', file), contents)
  }
  return directory
}

function calls(source: string) {
  return parse(source).program.body.flatMap((statement) => {
    if (statement.type !== 'ExpressionStatement' || statement.expression.type !== 'CallExpression') {
      return []
    }
    return [statement.expression.arguments.slice(1).map((argument) =>
      argument.type === 'StringLiteral' || argument.type === 'NumericLiteral' ? argument.value : undefined)]
  })
}

describe('translation extraction CLI', () => {
  it('extracts all 19 package appName strings from outside the package', () => {
    const directory = temporaryDirectory()
    const result = run(['extract-l10n-strings', 'translations.js'], directory)
    expect(result.status, result.stderr).toBe(0)
    const output = readFileSync(join(directory, 'translations.js'), 'utf8')
    const expected = [
      'pick a color', 'open', 'submit', 'undo color choice', 'restore palette',
      'factory reset palette', 'Custom Color',
      'Provided data is not a valid SVG image: "{data}".',
      'Choose a folder', 'Choose a prefix-folder', 'Choose {file}', 'Choose',
      'Invalid path selected: "{dir}".', 'Selected path: "{dir}/{base}/".',
      'Click to submit your changes.', 'Reset Changes', 'Clear Selection',
      'Please select an item!', 'An empty value is not allowed, please make your choice!',
    ]
    expect(calls(output).map(([text]) => text).sort()).toEqual(expected.sort())
    const comments = output.split('\n').filter((line) => line.startsWith('// TRANSLATORS:'))
    expect(comments).toHaveLength(19)
    const lineNumberedSource = /^\/\/ TRANSLATORS: Source: .+:\d+(?:, .+:\d+)*; generated by /
    expect(comments.every((line) => lineNumberedSource.test(line))).toBe(true)
    expect(output).toContain('@rotdrop/nextcloud-vue-components/lib/components/SelectWithSubmitButton.vue')
    expect(output).toContain('generated by nextcloud-vue-components extract-l10n-strings')
    expect(output).not.toContain('Nextcloud blue')
    expect(output).not.toContain('default-palette')
    const second = run(['extract-l10n-strings', 'translations.js'], directory)
    expect(second.status, second.stderr).toBe(0)
    expect(readFileSync(join(directory, 'translations.js'), 'utf8')).toBe(output)
  })

  it('parses Vue templates, both scripts, TS and JS; deduplicates and preserves literals and plurals', () => {
    const directory = fixture({
      'a.vue': `<template>
        <div :title="t(appName, 'Attribute')" v-if="true">
          {{ t(appName, 'Shared') as string }}
          {{ n(appName, 'One {file}', 'Many {file}', count) }}
          <span v-for="item in items">{{ t(appName, 'Loop') }}</span>
          {{ t('core', 'Core template') }}
          <!-- t(appName, 'Comment template') -->
        </div>
      </template>
      <script lang="ts">
        const label: string = translate(appName, 'Script');
      </script>
      <script setup lang="ts">
        const label = t(appName, 'Shared');
      </script>
      <style>.example::after { content: "t(appName, 'CSS')"; }</style>`,
      'b.ts': [
        "t(appName, 'Shared');",
        "const typed = <string>t(appName, 'Shared');",
        "translatePlural(appName, 'One {file}', 'Many {file}', count);",
        't(appName, "Quoted \\"text\\" and \\\\ slash\\nnext line");',
        't(appName, `Static template`);',
        "t('core', 'Core script');",
        "t(otherApp, 'Other app');",
        "// t(appName, 'Comment script');",
        'const example = "t(appName, \'String example\')";',
      ].join('\n'),
      'c.js': "t( /* domain */ appName,\n 'JavaScript');",
      'd.tsx': "const element = <div>{t(appName, 'JSX')}</div>;",
      'types.d.ts': 'This declaration file is not executable source.',
    })
    const result = run(['extract-l10n-strings', 'output.js'], directory, join(directory, 'bin/nextcloud-vue-components.mjs'))
    expect(result.status, result.stderr).toBe(0)
    const output = readFileSync(join(directory, 'output.js'), 'utf8')
    expect(calls(output)).toEqual([
      ['Script'], ['Shared'], ['Attribute'], ['One {file}', 'Many {file}', 1],
      ['Loop'], ['Quoted "text" and \\ slash\nnext line'], ['Static template'], ['JavaScript'], ['JSX'],
    ])
    const sharedComment = output.split('\n').find((line) => line.startsWith('// TRANSLATORS:') && line.includes('/b.ts'))
    expect(sharedComment).toContain('/a.vue:3')
    expect(sharedComment).toContain('/a.vue:14')
    expect(sharedComment).toContain('/b.ts:1')
    expect(sharedComment).toContain('/b.ts:2')
    expect(output).toContain('/a.vue:2')
    expect(output).toContain('/a.vue:4')
    expect(output).toContain('/a.vue:5')
    expect(output).toContain('/a.vue:11')
    expect(output).toContain('/c.js:1')
    expect(output).toContain('/d.tsx:1')
    expect(output).not.toMatch(/Core template|Core script|Other app|Comment template|Comment script|String example|CSS/)
  })

  it('works through the installed executable symlink', () => {
    const directory = temporaryDirectory()
    const executable = join(directory, 'nextcloud-vue-components')
    symlinkSync(cli, executable)
    const result = spawnSync(executable, ['extract-l10n-strings', 'output.js'], {
      cwd: directory,
      encoding: 'utf8',
    })
    expect(result.status, result.stderr).toBe(0)
    expect(calls(readFileSync(join(directory, 'output.js'), 'utf8'))).toHaveLength(19)
  })

  it('excludes exact package files from an app l10nignore, ignoring leading paths and unrelated entries', () => {
    const directory = fixture({
      'bare.ts': "t(appName, 'Bare');",
      'components/prefixed.vue': "<template>{{ t(appName, 'Prefixed') }}</template>",
      'absolute.js': "t(appName, 'Absolute');",
      'shared.ts': "t(appName, 'Shared');",
      'kept.ts': "t(appName, 'Shared'); t(appName, 'Kept');",
    })
    const app = temporaryDirectory()
    writeFileSync(join(app, '.l10nignore'), [
      '',
      '# @rotdrop/nextcloud-vue-components/lib/kept.ts',
      '  @rotdrop/nextcloud-vue-components/lib/bare.ts  ',
      'node_modules/@rotdrop/nextcloud-vue-components/lib/components/prefixed.vue',
      '/some/app/node_modules/@rotdrop/nextcloud-vue-components/lib/absolute.js',
      './node_modules/@rotdrop/nextcloud-vue-components/lib/shared.ts',
      'vendor/',
      'lib/kept.ts',
      'node_modules/@someone/nextcloud-vue-components/lib/kept.ts',
      'not-@rotdrop/nextcloud-vue-components/lib/kept.ts',
      '@rotdrop/nextcloud-vue-components/lib/*.ts',
      '@rotdrop/nextcloud-vue-components/lib/',
      '@rotdrop/nextcloud-vue-components/lib/missing.ts',
      '',
    ].join('\r\n'))
    const result = run(['extract-l10n-strings', 'output.js', '.l10nignore'], app,
      join(directory, 'bin/nextcloud-vue-components.mjs'))
    expect(result.status, result.stderr).toBe(0)
    const output = readFileSync(join(app, 'output.js'), 'utf8')
    expect(calls(output)).toEqual([['Shared'], ['Kept']])
    expect(output).toContain('/lib/kept.ts:1')
    expect(output).not.toContain('/lib/shared.ts')
  })

  it('skips excluded files before parsing and supports excluding every source', () => {
    const directory = fixture({ 'broken.ts': 'This is not valid TypeScript.' })
    const excludeFile = join(directory, '.l10nignore')
    writeFileSync(excludeFile, '@rotdrop/nextcloud-vue-components/lib/broken.ts\n')
    const result = run(['extract-l10n-strings', 'output.js', excludeFile], directory,
      join(directory, 'bin/nextcloud-vue-components.mjs'))
    expect(result.status, result.stderr).toBe(0)
    expect(calls(readFileSync(join(directory, 'output.js'), 'utf8'))).toEqual([])
  })

  it('reports an unreadable exclude file without overwriting the destination', () => {
    const directory = temporaryDirectory()
    writeFileSync(join(directory, 'output.js'), 'previous contents')
    const result = run(['extract-l10n-strings', 'output.js', 'missing.l10nignore'], directory)
    expect(result.status).toBe(1)
    expect(result.stderr).toContain('ENOENT')
    expect(result.stderr).toContain('missing.l10nignore')
    expect(readFileSync(join(directory, 'output.js'), 'utf8')).toBe('previous contents')
  })

  it.each([
    [],
    ['extract-l10n-strings'],
    ['extract-l10n-strings', 'output.js', '.l10nignore', 'extra'],
    ['extract-l10n-strings', 'output.js', ''],
    ['extract-l10n-strings', ''],
    ['unknown', 'output.js'],
  ])('rejects invalid arguments: %j', (...args) => {
    const directory = temporaryDirectory()
    const result = run(args, directory)
    expect(result.status).toBe(1)
    expect(result.stderr).toContain('Usage:')
  })

  it('reports help without generating a file', () => {
    const result = run(['--help'], temporaryDirectory())
    expect(result.status, result.stderr).toBe(0)
    expect(result.stdout).toContain('Usage:')
  })

  it.each([
    ['dynamic.ts', 't(appName, dynamic);', 'static string literals'],
    ['dynamic-template.vue', '<template>{{ t(appName, dynamic) }}</template>', 'static string literals'],
    ['broken.ts', 't(appName, "unterminated);', 'Unterminated string'],
    ['broken.vue', '<template><div></template>', 'missing end tag'],
    ['external.vue', '<template src="./template.html" />', 'External script and template'],
    ['pug.vue', '<template lang="pug">p Text</template>', 'Only HTML templates'],
  ])('reports extraction errors and preserves the previous destination for %s', (file, source, error) => {
    const directory = fixture({ [file]: source })
    writeFileSync(join(directory, 'output.js'), 'previous contents')
    const result = run(['extract-l10n-strings', 'output.js'], directory, join(directory, 'bin/nextcloud-vue-components.mjs'))
    expect(result.status).toBe(1)
    expect(result.stderr).toContain(`lib/${file}`)
    expect(result.stderr).toContain(error)
    expect(readFileSync(join(directory, 'output.js'), 'utf8')).toBe('previous contents')
  })

  it('reports write errors and refuses to overwrite a package source', () => {
    const directory = fixture({ 'a.js': "t(appName, 'Label')" })
    const executable = join(directory, 'bin/nextcloud-vue-components.mjs')
    const missingParent = run(['extract-l10n-strings', 'missing/output.js'], directory, executable)
    expect(missingParent.status).toBe(1)
    expect(missingParent.stderr).toContain('ENOENT')
    const sourceFile = run(['extract-l10n-strings', 'lib/a.js'], directory, executable)
    expect(sourceFile.status).toBe(1)
    expect(sourceFile.stderr).toContain('must not overwrite')
    writeFileSync(join(directory, '.l10nignore'), '@rotdrop/nextcloud-vue-components/lib/a.js')
    const excludedSourceFile = run(['extract-l10n-strings', 'lib/a.js', '.l10nignore'], directory, executable)
    expect(excludedSourceFile.status).toBe(1)
    expect(excludedSourceFile.stderr).toContain('must not overwrite')
    expect(readFileSync(join(directory, 'lib/a.js'), 'utf8')).toBe("t(appName, 'Label')")
  })
})
